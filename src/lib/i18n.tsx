const DICTS: Record<Lang, Dict> = { en, he, ar };
export type TKey = keyof Dict;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string; dir: "ltr" | "rtl" }>({
  lang: "en",
  setLang: () => {},
  t: (k) => en[k],
  dir: "ltr",
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = localStorage.getItem("ideaverse.lang") as Lang | null;
    if (saved && saved in DICTS) setLangState(saved);
  }, []);
  const dir = lang === "en" ? "ltr" : "rtl";
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);
  const setLang = (l: Lang) => {
    localStorage.setItem("ideaverse.lang", l);
    setLangState(l);
  };
  return <Ctx.Provider value={{ lang, setLang, t: (k) => DICTS[lang][k], dir }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
